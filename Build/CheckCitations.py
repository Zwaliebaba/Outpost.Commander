sys.path.insert(0, str(Path(__file__).resolve().parent))
from CheckProjectFiles import VENDORED_FILES, strip_cpp  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]
LIVING_DESIGN = "Docs/OutpostCommander.md"
ADR_DIRECTORY = "Docs/ADR"
REFERENCE_DIRECTORY = "Docs/Reference"
# Generated by Build/GenerateDocs.py from the gate tables, which may cite anything; so it may too.
OPEN_DECISIONS = f"{REFERENCE_DIRECTORY}/OpenDecisions.md"

CPP_EXTENSIONS = (".h", ".cpp", ".hlsl")
SOURCE_EXTENSIONS = CPP_EXTENSIONS + (".py",)
SKIPPED_DIRECTORIES = ("CompiledShader",)

# Where only what lasts may be cited: these documents, every .md directly in these directories but the exempt ones,
# and source comments.
FORM_DOCUMENTS = {"AGENTS.md", "CLAUDE.md", LIVING_DESIGN, "Docs/Glossary.md", "Docs/StyleGuide.md", "Docs/Pillars.md",
                  "Docs/Budgets.md", "Docs/Horizon.md"}
FORM_DIRECTORIES = (ADR_DIRECTORY, REFERENCE_DIRECTORY)
FORM_EXEMPT = {OPEN_DECISIONS}

ADR_FILE = re.compile(r"ADR-(\d{3})-.+\.md")
ADR = re.compile(r"\bADR-(\d{3})\b")
# One decision number; a fourth digit makes it something else, such as a year.
NUMBER = r"\d{1,3}(?!\d)"
SEPARATOR = r"(?:\s*,\s*(?:and\s+)?|\s+and\s+|\s+to\s+|\s*[–-]\s*)"
NUMBERS = rf"({NUMBER}(?:{SEPARATOR}{NUMBER})*)"
# An ADR, its link when the citation is one, an optional possessive, then the decisions.
ADR_DECISION = re.compile(r"\bADR-(\d{3})\b(?:\]\([^)\s]*\))?(?:'s)?\s+[Dd]ecisions?\s+" + NUMBERS)
OWN_DECISION = re.compile(r"(?<![\w-])[Dd]ecisions?\s+" + NUMBERS)
GAME_KEY = re.compile(r"\bGame\s+§([a-z0-9]+(?:\.[a-z0-9]+)*)")
HEADING_KEY = re.compile(r"\[§([a-z0-9]+(?:\.[a-z0-9]+)*)\]\s*$")
RETIRED_KEYS = re.compile(r"\s*(?:\*\*|__)?Retired keys\b[^:]*:(.*)")
RETIRED_KEY = re.compile(r"§([a-z0-9]+(?:\.[a-z0-9]+)*)|`§?([a-z0-9]+(?:\.[a-z0-9]+)*)`")
DECISION_ITEM = re.compile(r"(\d+)\. (.*)")

# The forms that do not last, in the order they are tried: a match inside an earlier one is not reported again, so
# `Phase N design §N` is one finding and not also a bare `design §N`.
FORMS = (
  ("a phase's design", re.compile(r"\b[Pp]hase\s+\d+(?:'s)?\s+designs?(?:'s)?(?:\s+§\s*\d+)?")),
  ("a phase's section", re.compile(r"\b[Pp]hase\s+\d+(?:'s)?\s+§\s*\d+")),
  ("the MVP's design", re.compile(r"\bMVP(?:'s)?\s+(?:designs?(?:'s)?(?:\s+§\s*\d+)?|§\s*\d+)")),
  ("a design section", re.compile(r"\b[Dd]esign(?:'s)?\s+§\s*\d+")),
  ("a task", re.compile(r"\b[Tt]asks?\s+(?:UI|LV|SP)?\d+\.\d+")),
  ("a task", re.compile(r"(?<![\w.])(?:UI|LV|SP)\d+\.\d+(?!\d)")),
  ("a gate", re.compile(r"\b[Gg]ates?\s+[A-Z]{1,2}\d+")),
  ("a milestone", re.compile(r"\b[Mm]ilestones?\s+(?:UI|LV|SP)?\d+\b")),
)
# A criterion, but not a compiler switch such as /W4.
CRITERION = re.compile(r"(?<![\w/\\-])(?:[QPST][1-5]|U[1-8]|W[1-6])(?![\w])")

FENCE = re.compile(r"[ \t]*(`{3,}|~{3,})")
CODE_SPAN = re.compile(r"(`+)(?!`)(.+?)(?<!`)\1(?!`)")
INLINE_LINK = re.compile(r"\]\(\s*(<[^>\n]*>|[^()\s]+(?:\([^()\s]*\)[^()\s]*)*)")
REFERENCE_DEFINITION = re.compile(r" {0,3}\[[^\]]+\]:\s*(<[^>\n]*>|\S+)")
HTML_LINK = re.compile(r"<(?:a|img)\b[^>]*?\s(?:href|src)\s*=\s*\"([^\"]+)\"")
EXPLICIT_ANCHOR = re.compile(r"<[A-Za-z][^>]*?\s(?:id|name)\s*=\s*[\"']([^\"']+)[\"']")
ATX_HEADING = re.compile(r" {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*")
SETEXT_UNDERLINE = re.compile(r" {0,3}(?:=+|-+)[ \t]*")
# A line that starts a block of its own, a quote, a table, HTML or a list item, and so is no setext heading's text.
BLOCK_START = re.compile(r" {0,3}(?:>|\||<|[*+-](?:\s|$)|\d+[.)](?:\s|$))")
LINE_ANCHOR = re.compile(r"L\d+(?:C\d+)?(?:-L\d+(?:C\d+)?)?")
URL_SCHEME = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")

# A line with nothing to read becomes this, which no pattern's whitespace crosses: a citation runs on from one comment
# line to the next, but not over a line of code or a blank line.
NOTHING = "\0"


@dataclasses.dataclass(frozen=True, order=True)
class Finding:
  path: str
  line: int
  check: str
  message: str

  def __str__(self):
    return f"{self.path}:{self.line}: [{self.check}] {self.message}"


@dataclasses.dataclass
class Text:
  """What a file has to read: its readable text, with everything else blanked and its lines kept, and, for Markdown,
  the same with fenced code blocks blanked too, which is where links are looked for."""
  path: str
  kind: str          # "source" or "markdown"
  readable: str
  linkable: str

  def __post_init__(self):
    self.newlines = [index for index, character in enumerate(self.readable) if character == "\n"]
    self.link_newlines = [index for index, character in enumerate(self.linkable) if character == "\n"]

  def line_of(self, _offset):
    return bisect.bisect_right(self.newlines, _offset - 1) + 1

  def link_line_of(self, _offset):
    return bisect.bisect_right(self.link_newlines, _offset - 1) + 1


@dataclasses.dataclass
class Adr:
  path: str
  decisions: dict    # number: True when it is retired
  has_decision_section: bool


class Tree:
  """The tree a run reads, all relative to one root: its files, its ADRs, its living design's keys and the anchors of
  each Markdown file, each read once."""

  def __init__(self, _root):
    self.root = _root
    self.files = self.list_files()
    self.adrs = self.read_adrs()
    self.keys, self.retired_keys, self.key_findings = self.read_keys()
    self._anchors = {}

  def list_files(self):
    result = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=self.root,
                            capture_output=True)
    if result.returncode != 0:
      raise SystemExit(f"CheckCitations: 'git ls-files' failed: {result.stderr.decode(errors='replace').strip()}")
    files = set()
    for name in result.stdout.decode().split("\0"):
      if not name or not (self.root / name).is_file():
        continue
      if any(part in SKIPPED_DIRECTORIES for part in Path(name).parts) or name in VENDORED_FILES:
        continue
      if name.endswith(SOURCE_EXTENSIONS + (".md",)):
        files.add(name)
    return sorted(files)

  def text(self, _path):
    try:
      return (self.root / _path).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    except (OSError, UnicodeDecodeError) as error:
      raise SystemExit(f"CheckCitations: {_path} cannot be read: {error}")

  def read_adrs(self):
    adrs = {}
    directory = self.root / ADR_DIRECTORY
    for path in sorted(directory.glob("ADR-*.md")) if directory.is_dir() else []:
      name = ADR_FILE.fullmatch(path.name)
      if name is None:
        continue
      relative = f"{ADR_DIRECTORY}/{path.name}"
      decisions = {}
      in_decision = False
      seen_section = False
      for line in self.text(relative).split("\n"):
        if line.startswith("## "):
          in_decision = line.rstrip() == "## Decision"
          seen_section = seen_section or in_decision
          continue
        item = DECISION_ITEM.match(line) if in_decision else None
        if item:
          decisions[int(item.group(1))] = item.group(2).startswith("*(retired)*")
      adrs[name.group(1)] = Adr(relative, decisions, seen_section)
    return adrs

  def read_keys(self):
    """The living design's keys, its retired keys and what is wrong with its headings, or None for the first when it
    does not exist."""
    if not (self.root / LIVING_DESIGN).is_file():
      return None, set(), []
    keys = {}
    retired = set()
    findings = []
    for number, heading in markdown_headings(self.text(LIVING_DESIGN)):
      key = HEADING_KEY.search(heading)
      if key is None:
        continue
      if key.group(1) in keys:
        findings.append(Finding(LIVING_DESIGN, number, "key", f"two headings have the key §{key.group(1)}: this one "
                                                              f"and line {keys[key.group(1)]}'s"))
      else:
        keys[key.group(1)] = number
    for line in self.text(LIVING_DESIGN).split("\n"):
      match = RETIRED_KEYS.match(line)
      if match:
        retired |= {first or second for first, second in RETIRED_KEY.findall(match.group(1))}
    return set(keys), retired, findings

  def anchors(self, _path):
    if _path not in self._anchors:
      text = self.text(_path)
      anchors = set(EXPLICIT_ANCHOR.findall(text))
      used = {}
      for _, heading in markdown_headings(text):
        slug = github_slug(heading)
        if slug in used:
          base = slug
          while slug in used:
            used[base] += 1
            slug = f"{base}-{used[base]}"
        used[slug] = 0
        anchors.add(slug)
      self._anchors[_path] = anchors
    return self._anchors[_path]


# ── Reading a file's text. ──────────────────────────────────────────────────────────────────────────────────────


def fence_after(_line, _fence):
  """The fence a Markdown line leaves open: _fence is the one open before it, or None."""
  opening = FENCE.match(_line)
  if _fence is None:
    return opening.group(1) if opening else None
  if opening and opening.group(1)[0] == _fence[0] and len(opening.group(1)) >= len(_fence) and \
      _line.strip() == opening.group(1):
    return None
  return _fence


def blank(_text):
  return "".join("\n" if character == "\n" else " " for character in _text)


def blank_code_spans(_line):
  return CODE_SPAN.sub(lambda match: blank(match.group(0)), _line)


def finish(_lines):
  return "\n".join(line if line.strip() else NOTHING for line in _lines)


def markdown_headings(_text):
  """Each heading of a Markdown text, ATX or setext, outside code blocks, with its line number, as GitHub renders its
  text: links and images keep only their text, and HTML tags go."""
  headings = []
  fence = None
  paragraph = None   # the line before, when it is a line of a paragraph
  for index, line in enumerate(_text.split("\n")):
    was_open = fence is not None
    fence = fence_after(line, fence)
    if was_open or fence is not None:
      paragraph = None
      continue
    atx = ATX_HEADING.fullmatch(line)
    if atx:
      headings.append((index + 1, atx.group(2) or ""))
      paragraph = None
      continue
    if paragraph is not None and SETEXT_UNDERLINE.fullmatch(line):
      headings.append((index, paragraph))
      paragraph = None
      continue
    starts_a_block = BLOCK_START.match(line) or line.startswith((" " * 4, "\t"))
    paragraph = line.strip() if line.strip() and not starts_a_block and not SETEXT_UNDERLINE.fullmatch(line) else None
  rendered = []
  for number, heading in headings:
    heading = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    heading = re.sub(r"!?\[([^\]]*)\]\[[^\]]*\]", r"\1", heading)
    rendered.append((number, re.sub(r"<[^>]+>", "", heading)))
  return rendered


def github_slug(_heading):
  """The anchor GitHub gives a heading: lowercase, every character but letters, digits, marks, spaces, hyphens and
  underscores dropped, and each space a hyphen. A repeated slug takes -1, -2 and so on, which Tree.anchors adds."""
  kept = [character for character in _heading.strip().lower()
          if character in " -_" or unicodedata.category(character)[0] in "LM" or
          unicodedata.category(character) in ("Nd", "Nl", "Pc")]
  return "".join(kept).replace(" ", "-")


def markdown_text(_path, _text):
  readable = []
  linkable = []
  fence = None
  for line in _text.split("\n"):
    was_open = fence is not None
    fence = fence_after(line, fence)
    if was_open or fence is not None:
      readable.append(line)
      linkable.append(blank(line))
    else:
      spans_blanked = blank_code_spans(line)
      readable.append(spans_blanked)
      linkable.append(spans_blanked)
  return Text(_path, "markdown", finish(readable), "\n".join(linkable))


def strip_comment_markers(_line):
  line = re.sub(r"/{2,}!?|/\*+!?|\*+/", lambda match: " " * len(match.group(0)), _line)
  return re.sub(r"^(\s*)\*+(?=\s|$)", lambda match: match.group(1) + " " * (len(match.group(0)) - len(match.group(1))),
                line)


def cpp_text(_path, _text):
  """The comments of a .h, .cpp or .hlsl file, with the code, the string literals and the comment markers blanked."""
  without_comments = strip_cpp(_text, True)
  comments = "".join(original if original != kept else ("\n" if original == "\n" else " ")
                     for original, kept in zip(_text, without_comments))
  lines = [blank_code_spans(strip_comment_markers(line)) for line in comments.split("\n")]
  return Text(_path, "source", finish(lines), "")


def python_text(_path, _text):
  """The comments and docstrings of a .py file, with everything else blanked."""
  lines = _text.split("\n")
  kept = [""] * len(lines)
  try:
    for token in tokenize.generate_tokens(io.StringIO(_text).readline):
      if token.type == tokenize.COMMENT:
        row, column = token.start
        kept[row - 1] = " " * (column + 1) + token.string[1:]
    tree = ast.parse(_text)
  except (tokenize.TokenError, SyntaxError) as error:
    raise SystemExit(f"CheckCitations: {_path} is not Python this can read: {error}")
  for node in ast.walk(tree):
    if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) or not node.body:
      continue
    first = node.body[0]
    if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
      for row in range(first.lineno, first.end_lineno + 1):
        kept[row - 1] = lines[row - 1]
  return Text(_path, "source", finish(blank_code_spans(line) for line in kept), "")


def read(_tree, _path):
  text = _tree.text(_path)
  if _path.endswith(".md"):
    return markdown_text(_path, text)
  if _path.endswith(".py"):
    return python_text(_path, text)
  return cpp_text(_path, text)


# ── Checks. Each takes the tree and one file's text and returns findings. ──────────────────────────────────────


def forms_apply(_path):
  if _path.endswith(SOURCE_EXTENSIONS):
    return True
  if _path in FORM_EXEMPT:
    return False
  return _path in FORM_DOCUMENTS or posixpath.dirname(_path) in FORM_DIRECTORIES


def criteria_apply(_path):
  return _path.endswith(SOURCE_EXTENSIONS) or posixpath.dirname(_path) == ADR_DIRECTORY


def own_adr(_path):
  if posixpath.dirname(_path) != ADR_DIRECTORY:
    return None
  name = ADR_FILE.fullmatch(posixpath.basename(_path))
  return name.group(1) if name else None


def cited_numbers(_text):
  """The decisions a run of numbers names: each number, and for "N to M" both ends, as (number, is a range's end)."""
  tokens = re.findall(r"\d+|to|[–-]", _text)
  cited = []
  index = 0
  while index < len(tokens):
    if index + 2 < len(tokens) and tokens[index + 1] in ("to", "–", "-"):
      cited.append((int(tokens[index]), int(tokens[index + 2])))
      index += 3
    else:
      cited.append((int(tokens[index]), None))
      index += 1
  return cited


def decision_findings(_tree, _text, _match, _number, _numbers_group):
  findings = []
  line = _text.line_of(_match.start())
  adr = _tree.adrs.get(_number)
  if adr is None:
    return findings  # the adr check reports an ADR with no file
  for first, last in cited_numbers(_match.group(_numbers_group)):
    where = f"ADR-{_number} decision {first}" if last is None else f"ADR-{_number} decisions {first} to {last}"
    if not adr.decisions:
      findings.append(Finding(_text.path, line, "decision", f"cites {where}, and ADR-{_number} has " +
                              ("no numbered decisions" if adr.has_decision_section else "no ## Decision section")))
      continue
    if last is not None and last <= first:
      findings.append(Finding(_text.path, line, "decision", f"cites {where}, a range that runs backward"))
    for end in (first,) if last is None else (first, last):
      if end not in adr.decisions:
        findings.append(Finding(_text.path, line, "decision", f"cites {where}, and ADR-{_number} has no decision "
                                                               f"{end}; its decisions are 1 to {max(adr.decisions)}"))
      elif adr.decisions[end]:
        findings.append(Finding(_text.path, line, "decision", f"cites {where}, and ADR-{_number} decision {end} is "
                                                               "retired; cite where its subject went"))
  return findings


def check_adrs(_tree, _text):
  findings = []
  for match in ADR.finditer(_text.readable):
    if match.group(1) not in _tree.adrs:
      findings.append(Finding(_text.path, _text.line_of(match.start()), "adr",
                              f"cites ADR-{match.group(1)}, which has no file in {ADR_DIRECTORY}/"))
  return findings


def check_decisions(_tree, _text):
  findings = []
  spans = []
  for match in ADR_DECISION.finditer(_text.readable):
    spans.append(match.span())
    findings += decision_findings(_tree, _text, match, match.group(1), 2)
  own = own_adr(_text.path)
  if own is not None:
    for match in OWN_DECISION.finditer(_text.readable):
      if not any(start <= match.start() < end for start, end in spans):
        findings += decision_findings(_tree, _text, match, own, 1)
  return findings


def check_keys(_tree, _text):
  findings = list(_tree.key_findings) if _text.path == LIVING_DESIGN else []
  for match in GAME_KEY.finditer(_text.readable):
    key = match.group(1)
    line = _text.line_of(match.start())
    if _tree.keys is None:
      findings.append(Finding(_text.path, line, "key", f"cites Game §{key}, and {LIVING_DESIGN} does not exist"))
    elif key in _tree.retired_keys:
      findings.append(Finding(_text.path, line, "key", f"cites Game §{key}, which is a retired key of {LIVING_DESIGN}"))
    elif key not in _tree.keys:
      findings.append(Finding(_text.path, line, "key", f"cites Game §{key}, which no heading of {LIVING_DESIGN} has"))
  return findings


def link_targets(_text):
  """Every relative link of a Markdown text, as (offset, target), outside code."""
  targets = []
  for pattern in (INLINE_LINK, HTML_LINK):
    targets += [(match.start(1), match.group(1)) for match in pattern.finditer(_text.linkable)]
  offset = 0
  for line in _text.linkable.split("\n"):
    definition = REFERENCE_DEFINITION.match(line)
    if definition:
      targets.append((offset + definition.start(1), definition.group(1)))
    offset += len(line) + 1
  return sorted(targets)


def resolve(_from, _target):
  """The repository path a link names, its anchor, and whether it is relative at all."""
  target = _target[1:-1] if _target.startswith("<") and _target.endswith(">") else _target
  if URL_SCHEME.match(target) or target.startswith("//"):
    return None, None
  path, _, fragment = target.partition("#")
  path = urllib.parse.unquote(path)
  if not path:
    return _from, urllib.parse.unquote(fragment)
  if path.startswith("/"):
    resolved = posixpath.normpath(path.lstrip("/"))
  else:
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(_from), path))
  return resolved, urllib.parse.unquote(fragment)


def check_links(_tree, _text):
  findings = []
  if _text.kind != "markdown":
    return findings
  for offset, target in link_targets(_text):
    resolved, fragment = resolve(_text.path, target)
    if resolved is None:
      continue
    line = _text.link_line_of(offset)
    if resolved == ".." or resolved.startswith("../"):
      findings.append(Finding(_text.path, line, "link", f"links to {target}, which is outside the repository"))
      continue
    path = _tree.root / resolved
    if not path.exists():
      findings.append(Finding(_text.path, line, "link", f"links to {target}, and {resolved} does not exist"))
      continue
    if not fragment:
      continue
    if path.is_file() and resolved.endswith(".md"):
      if fragment not in _tree.anchors(resolved):
        findings.append(Finding(_text.path, line, "link", f"links to {target}, and {resolved} has no heading or "
                                                           f"<a id> whose anchor is \"{fragment}\""))
    elif not LINE_ANCHOR.fullmatch(fragment):
      findings.append(Finding(_text.path, line, "link", f"links to {target}, and {resolved} is not Markdown, so its "
                                                         "only anchors are lines, #L<n>"))
  return findings


def check_forms(_tree, _text):
  findings = []
  if not forms_apply(_text.path):
    return findings
  taken = []
  patterns = list(FORMS)
  if criteria_apply(_text.path):
    patterns.append(("a criterion", CRITERION))
  for what, pattern in patterns:
    for match in pattern.finditer(_text.readable):
      if any(start < match.end() and match.start() < end for start, end in taken):
        continue
      taken.append(match.span())
      cited = re.sub(r"\s+", " ", match.group(0)).strip()
      findings.append(Finding(_text.path, _text.line_of(match.start()), "form",
                              f"cites {what}, \"{cited}\", which does not last; cite an ADR decision or a section of "
                              "the living design by its key"))
  return findings


CHECKS = (check_adrs, check_decisions, check_keys, check_links, check_forms)


def run_checks(_root):
  tree = Tree(_root)
  findings = set()
  for path in tree.files:
    text = read(tree, path)
    for check in CHECKS:
      findings.update(check(tree, text))
  return sorted(findings), len(tree.files)


