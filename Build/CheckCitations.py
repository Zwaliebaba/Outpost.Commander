def self_test():
  failures = 0
  with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as scratch:
    pristine = Path(scratch) / "pristine"
    build_fixture(pristine)
    baseline, _ = run_checks(pristine)
    ok = not baseline
    failures += not ok
    print(f"{'pass' if ok else 'FAIL'}  (quiet) the unbroken tree has no findings")
    for finding in baseline:
      print(f"        {finding}")

    cases = [(check, description, mutate, True) for check, description, mutate in SELF_TEST_CASES]
    cases += [(None, description, mutate, False) for description, mutate in SELF_TEST_QUIET]
    for index, (check, description, mutate, should_fire) in enumerate(cases):
      case = Path(scratch) / f"case{index}"
      shutil.copytree(pristine, case)
      mutate(case)
      findings, _ = run_checks(case)
      added = sorted(set(findings) - set(baseline))
      fired = [finding for finding in added if finding.check == check] if should_fire else added
      ok = bool(fired) == should_fire
      failures += not ok
      label = f"[{check}] {description}" if should_fire else f"(quiet) {description}"
      print(f"{'pass' if ok else 'FAIL'}  {label}")
      if not ok or (should_fire and len(added) > len(fired)):
        for finding in added:
          print(f"        {finding}")
      shutil.rmtree(case, ignore_errors=True)
    total = len(cases) + 1
  print(f"\n{total - failures} of {total} self-test cases passed.")
  return 1 if failures else 0


def main():
  parser = argparse.ArgumentParser(description="Check every citation and relative link in the tree (AGENTS.md §8).")
  parser.add_argument("--self-test", action="store_true", help="show that each check fires on a broken small tree")
  args = parser.parse_args()
  if args.self_test:
    return self_test()

  findings, files = run_checks(REPO_ROOT)
