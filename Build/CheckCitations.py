#!/usr/bin/env python3
"""The citation gate of AGENTS.md §8.

Code, the ADRs, the living design and the living references cite only what lasts: an ADR, one of its numbered
decisions, and a section of the living design by its key. Everything else a document might point at, a plan's task, a
gate, a milestone, a phase's design, is transient and goes when its plan closes. This reads every citation and every
relative link in the tree, and fails on any that does not resolve, and on any citation of what does not last where
only what lasts may be cited:

  adr        an `ADR-NNN` with no Docs/ADR/ADR-NNN-*.md
  decision   an `ADR-NNN decision N` whose decision does not exist or reads `N. *(retired)*`, and the same of
             `decisions N and M`, `decisions N, M and P` and `decisions N to M`, whose two ends are checked; in an ADR,
             a `decision N` that names no ADR is one of its own
  key        a `Game §<key>` whose key is not the `[§<key>]` of a heading in Docs/OutpostCommander.md, or is on its
             "Retired keys" line (written there as `§<key>` or in a code span)
  link       a relative Markdown link, image or reference definition whose file does not exist or lies outside the
             repository, or whose #anchor is neither an explicit `<a id="...">` nor the GitHub slug of a heading in the
             file it names; a file that is not Markdown takes only a line anchor, `#L<n>` or `#L<n>-L<m>`
  form       a citation of what does not last: a phase's design (`Phase N design`, `Phase N §N`), the MVP's
             (`MVP design`, `MVP §N`), a bare `design §N`, a task (`task N.N`, `tasks ...`, and the UI, LV and SP task
             ids), a gate (`gate X#`, `gates ...`), a milestone (`milestone N`), and a criterion (Qn, Pn, Sn, Tn, Un
             and Wn, as the phase designs number them)

The existence checks, adr, decision, key and link, hold everywhere. The form check holds in the code, the ADRs, the
living design and the living references: source comments and docstrings, Docs/ADR/*.md, Docs/OutpostCommander.md,
Docs/Glossary.md, Docs/StyleGuide.md, Docs/Pillars.md, Docs/Budgets.md, Docs/Horizon.md, Docs/Reference/*.md, AGENTS.md
and CLAUDE.md.
Its criteria hold in source comments and the ADRs only, where an outcome is never the thing to cite. Everything under
Docs/Plans/ (the plans, the open phase's design and the self-play network's blueprint) and Docs/Records/, and
Docs/Reference/OpenDecisions.md, which GenerateDocs.py writes from the gate tables, may cite anything, as long as it
exists.

What it reads: every .h, .cpp, .hlsl, .py and .md file git tracks, and every new one it does not ignore, so a file not
yet added is read before you push. In a .h, .cpp or .hlsl file it reads the comments and nothing else; in a .py file,
the comments and the docstrings; in a .md file, the text. A code span, in a comment as in Markdown, is a literal and is
not read, which is how a document writes a citation's form without citing anything. A fenced code block in Markdown is
read for citations, since a diagram can cite, but holds no links. CompiledShader/ is build output (AGENTS.md §2) and
the vendored d3dx12.h is upstream's text (ADR-007), and neither is read.

It does not parse C++ or Markdown. A citation is found by its words, so one that a comment breaks across two lines is
still one citation, and a run of decision numbers is read as far as its commas, "and" and "to" carry it.

Usage:
  python Build/CheckCitations.py              check the tree
  python Build/CheckCitations.py --self-test  build a small tree, break it once per check, and show each check fires

Exit status: 0 when every citation and link resolves and none cites what does not last, 1 when there are findings (or
a self-test case failed), 2 when the tree could not be read.
"""

